    private static boolean isAlertStatus(String s) {
        return s != null && (s.contains("告警") || s.contains("预警") || s.contains("高风险")
                || s.contains("返工") || s.contains("退回") || s.contains("失败"));
    }

    private static boolean isPendingStatus(String s) {
        return s != null && (s.contains("审批中") || s.contains("待审") || s.contains("待")
                || s.contains("质控") || s.contains("在途"));
    }

