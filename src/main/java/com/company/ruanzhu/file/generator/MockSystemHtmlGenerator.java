    /** 取样例行中第 i 个值；越界时返回空串 */
    private static String valueAt(String[] sample, int i) {
        return (sample != null && i >= 0 && i < sample.length) ? sample[i] : "";
    }

    /** 简单 HTML 转义，避免样例值破坏标签结构 */
    private static String escape(String s) {
        return s == null ? "" : s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
                .replace("\"", "&quot;").replace("'", "&#39;");
    }

    /** 渲染单个字段：返回一段 HTML 字符串；required 控制是否显示 *，value 非空时预填 */
    private String renderField(String label, boolean required, String value) {
        String placeholder = label.replace("(", "（").replace(")", "）");
        String val = (value == null || value.isEmpty()) ? "" : " value='" + escape(value) + "'";
        return "<div class='form-item'><label class='form-label'>"
                + (required ? "<span class='req'>*</span>" : "") + label + "</label>"
                + "<input class='form-input' placeholder='请输入" + placeholder + "'" + val + "></div>";
    }
